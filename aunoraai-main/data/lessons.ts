export type Lesson = {
  id: number;
  courseId: number;
  title: string;
  order: number;
  duration: string;
  is_free: boolean;
  isQuiz?: boolean; // bài kiểm tra sau mỗi 5 bài / cuối khóa
};

function buildLessons(
  courseId: number,
  titles: string[],
  is_free: boolean,
  startId: number
): Lesson[] {
  const list: Lesson[] = [];
  let id = startId;
  let order = 1;

  titles.forEach((title, index) => {
    list.push({
      id: id++,
      courseId,
      title,
      order: order++,
      duration: index % 5 === 4 ? "20 phút" : "15–25 phút",
      is_free,
      isQuiz: false,
    });
    // Sau mỗi 5 bài → 1 bài kiểm tra
    if ((index + 1) % 5 === 0) {
      list.push({
        id: id++,
        courseId,
        title: `Kiểm tra số ${(index + 1) / 5}`,
        order: order++,
        duration: "15 phút",
        is_free,
        isQuiz: true,
      });
    }
  });

  // Kiểm tra cuối khóa
  list.push({
    id: id++,
    courseId,
    title: "Kiểm tra tổng kết cuối khóa",
    order: order++,
    duration: "25 phút",
    is_free,
    isQuiz: true,
  });

  return list;
}

